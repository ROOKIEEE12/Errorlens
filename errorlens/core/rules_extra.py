# ---------- JS runtime ----------
def _cannot_read(lines, i, m, ctx):
    prop = m.group("prop")
    return RuleResult(
        error_type="cannot_read_properties", title=f"Cannot read '{prop}' of undefined/null",
        root_cause=f"Code accessed '.{prop}' on a value that was undefined or null — usually data that has not loaded yet, a missing prop, or an env/config value that was never set.",
        fix_steps=[
            "Open the file at the suspected location and find the expression that reads the property; log or inspect the value before it.",
            f"Guard the access (optional chaining like value?.{prop}) or provide a default — and fix why the value is empty (missing prop, failed fetch, wrong key).",
            "If this happens during prerender/build, make sure the data source or env vars are available at build time.",
        ],
        verify=[_build_cmd(ctx)],
        risk=("low", "Local code change. Optional chaining can hide a real data bug, so also fix the upstream cause."),
        confidence=0.8, key=prop, file=_find_file(lines, i, before=2, after=8))


def _enoent(lines, i, m, ctx):
    path = m.group("path")
    return RuleResult(
        error_type="file_not_found", title=f"File not found: {path}",
        root_cause=f"The process tried to open '{path}' but it does not exist in the build environment (not committed, wrong relative path, case mismatch, or generated by an earlier step that did not run).",
        fix_steps=[
            f"Check that '{path}' exists in the repository (and is not gitignored) with exactly this casing.",
            "If it is generated, make sure the generating step runs before this command (e.g. prisma generate, codegen, build order).",
            "Prefer paths built from the project root (path.join(process.cwd(), ...)) instead of relative ones.",
        ],
        verify=[f"ls -la {path}", _build_cmd(ctx)],
        risk=("low", "Adds or corrects a file path; no behaviour change expected."),
        confidence=0.85, key=re.sub(r"[0-9]+", "N", path), file=_find_file(lines, i))


def _node_cannot_find(lines, i, m, ctx):
    mod = m.group("module")
    is_path = mod.startswith(("/", ".", "<ROOT>")) or "/" in mod and not mod.startswith("@")
    return RuleResult(
        error_type="node_module_not_found", title=f"Node cannot find module '{mod}'",
        root_cause=(f"Node tried to load '{mod}' and it is not there — " + (
            "a local file path that does not exist (wrong path, not built yet, or not copied into the image)."
            if is_path else "the package is not installed or is missing from dependencies.")),
        fix_steps=[
            ("Verify the file exists and that the build step producing it (tsc/build) ran first." if is_path
             else f"Install it: {ctx.package_manager or 'npm'} {'add' if ctx.package_manager in ('pnpm','yarn') else 'install'} {mod.split('/')[0] if not mod.startswith('@') else '/'.join(mod.split('/')[:2])}"),
            "Check package.json (dependencies vs devDependencies) — production installs skip devDependencies.",
            "Reinstall from the lockfile and re-run.",
        ],
        verify=["npm ci", _build_cmd(ctx)],
        risk=("low", "Adds a dependency or fixes a path. Pin versions and commit the lockfile."),
        confidence=0.85, key=re.sub(r"[0-9]+", "N", mod), file=_find_file(lines, i))


def _eresolve(lines, i, m, ctx):
    found = next((l for l in lines[i:i + 12] if "Found:" in l), "")
    conflict = next((l for l in lines[i:i + 14] if "peer " in l), "")
    detail = (found.strip() + " / " + conflict.strip()).strip(" /")
    return RuleResult(
        error_type="dependency_conflict", title="npm cannot resolve the dependency tree",
        root_cause="Two packages require incompatible versions of the same dependency (peer dependency conflict)." + (f" Detail: {detail}" if detail else ""),
        fix_steps=[
            "Read the 'Found' / 'peer' lines to see which two packages disagree and on which version.",
            "Upgrade or downgrade one side so both accept the same version (check the package's release notes for compatibility).",
            "Reinstall cleanly and commit the updated lockfile. Avoid --force / --legacy-peer-deps as a permanent fix.",
        ],
        verify=["rm -rf node_modules", "npm install", _build_cmd(ctx)],
        risk=("high", "Dependency changes can break runtime behaviour. Do not use --force or --legacy-peer-deps just to silence the error."),
        confidence=0.88, key=re.sub(r"[\d.]+", "N", detail) or "eresolve", file=None)


def _missing_script(lines, i, m, ctx):
    sc = m.group("script")
    return RuleResult(
        error_type="missing_npm_script", title=f"Missing npm script '{sc}'",
        root_cause=f"The command runs 'npm run {sc}' but package.json has no such script.",
        fix_steps=[f"Add a '{sc}' entry under \"scripts\" in package.json (e.g. \"{sc}\": \"next build\").",
                   "If the host (Vercel/CI) uses a custom build command, check it matches an existing script.",
                   "Commit package.json and re-run."],
        verify=[f"npm run {sc}"],
        risk=("low", "Config-only change."), confidence=0.9, key=sc, file=None)


# ---------- Docker ----------
def _docker_copy(lines, i, m, ctx):
    path = m.group("path")
    loc = None
    for l in lines:
        dm = re.search(r"Dockerfile:(\d+)", l)
        if dm:
            loc = SuspectedFile(path="Dockerfile", line=int(dm.group(1)), confidence=0.75)
            break
    return RuleResult(
        error_type="docker_copy_failed", title=f"Docker COPY cannot find '{path}'",
        root_cause=f"The build context does not contain '{path}': wrong path, wrong build context directory, or it is excluded by .dockerignore.",
        fix_steps=[
            f"Confirm '{path}' exists relative to the build context (the directory you pass to 'docker build').",
            "Check .dockerignore is not excluding it, and that COPY paths are relative to the context, not the Dockerfile.",
            "Fix the COPY source path or the build context argument, then rebuild.",
        ],
        verify=["docker build --no-cache -t my-app:debug ."],
        risk=("low", "Only changes a file path in the Dockerfile or .dockerignore."),
        confidence=0.9, key=path, file=loc or SuspectedFile(path="Dockerfile", confidence=0.5))


# ---------- GitHub Actions ----------
def _gha_input(lines, i, m, ctx):
    name = m.group("input")
    return RuleResult(
        error_type="gha_missing_input", title=f"Action input '{name}' not supplied",
        root_cause=f"A step requires the input '{name}' but it resolved to empty — usually a secret that is not defined for this repo/environment, or one that is unavailable to PRs from forks.",
        fix_steps=[
            "Repo Settings → Secrets and variables → Actions: confirm the secret exists with this exact name.",
            "If the run is a fork PR or a different environment, secrets are not passed — use an environment or guard the step.",
            "Re-run the failed job.",
        ],
        verify=["gh secret list"],
        risk=("medium", "Secrets are sensitive: never echo them and never paste values into the workflow file."),
        confidence=0.9, key=name, file=SuspectedFile(path=".github/workflows", confidence=0.4))


def _gha_invalid_workflow(lines, i, m, ctx):
    f, ln = m.group("file"), int(m.group("line"))
    return RuleResult(
        error_type="gha_invalid_workflow", title="Invalid workflow file",
        root_cause=f"GitHub rejected the workflow file {f} near line {ln} (YAML syntax or schema error — often indentation or a wrong key).",
        fix_steps=[f"Open {f} at line {ln} and check indentation (spaces only) and key names.",
                   "Validate the file with actionlint or an editor with the GitHub Actions schema.",
                   "Commit the fix and re-run."],
        verify=["actionlint"],
        risk=("low", "Workflow config only."), confidence=0.9, key="invalid_workflow",
        file=SuspectedFile(path=f, line=ln, confidence=0.9))


# ---------- Next.js prerender (last resort) ----------
def _prerender(lines, i, m, ctx):
    page = m.group("page")
    return RuleResult(
        error_type="prerender_failure", title=f"Prerender failed for {page}",
        root_cause=f"Next.js failed to statically generate '{page}'. No underlying error line was recognised, so read the lines right after this one for the real exception.",
        fix_steps=[f"Find the first exception printed after the prerender message for page '{page}'.",
                   "Check data fetching and env vars used by that page at build time.",
                   "Reproduce with a local production build."],
        verify=[_build_cmd(ctx)],
        risk=("low", "Diagnostic step; no change proposed."), confidence=0.5, key=page, file=None)


_COPY_PATS = [
    r"failed to compute cache key: .*?\"/(?P<path>[^\"]+)\": not found",
    r"failed to calculate checksum of ref [^:]+: \"/(?P<path>[^\"]+)\": not found",
    r"COPY failed: file not found in build context or excluded by \.dockerignore: stat (?P<path>\S+): file does not exist",
]

